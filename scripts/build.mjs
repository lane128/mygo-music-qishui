// Build-time only. The installed plugin executes the standalone output without
// esbuild, Node module loading or a package manager in MyGO's sandbox.
import { build } from 'esbuild'
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const result = await build({
  absWorkingDir: root, entryPoints: ['src/plugin.mjs'], bundle: true,
  format: 'esm', platform: 'neutral', target: 'es2022', charset: 'utf8',
  write: false, metafile: true, logLevel: 'silent',
  banner: { js: '// Generated by npm run build. Edit src/plugin.mjs and the shared helper modules.' },
})
if (Object.keys(result.metafile.inputs).some(name => /(?:^|\/)(?:native|catalog|scene-art|playback|worker)\.mjs$/.test(name))) {
  throw new Error('Sandbox bundle unexpectedly includes a Node runtime module.')
}
const output = new URL('../index.js', import.meta.url)
const text = result.outputFiles[0].text
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== text) throw new Error('index.js is stale. Run npm run build before testing or packaging.')
} else await writeFile(output, text)
