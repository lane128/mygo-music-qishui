// A resource and its authorization remain paired; AAC stays M4A and keeps its source quality.
test('uses one signed grant and returns actual host format and quality', async () => {
  let requests = 0
  const payload = grant([candidate('aac', 'higher', 'auth-aac'), candidate('flac', 'lossless', 'auth-flac')])
  for (const [quality, auth, source, expectedQuality] of [['standard', 'auth-aac', aac, 'standard'], ['lossless', 'auth-flac', flac, 'lossless']]) {
    const result = await resolvePlayback(session, { id, quality }, {
      requestJSON: async (account, endpoint, options) => {
        requests++
        assert.equal(account, session)
        assert.equal(endpoint, '/luna/pc/track_v2')
        assert.equal(options.signed, true)
        assert.deepEqual(options.body, { track_id: id, media_type: 'track', queue_type: 'favorite_track_playlist', scene_name: 'library' })
        return payload
      },
      download: async url => { assert.equal(url, payload.track_player.video_model.video_list[quality === 'standard' ? 0 : 1].main_url); return source },
      decode: async (bytes, matchingAuth) => { assert.equal(matchingAuth, auth); return bytes },
    })
    assert.deepEqual(result.data, source)
    assert.equal(result.type, quality === 'standard' ? 'm4a' : 'flac')
    assert.equal(result.quality, expectedQuality)
    assert.equal(result.bitRate, quality === 'standard' ? 256000 : 900000)
    assert.deepEqual(Object.keys(result).sort(), ['bitRate', 'data', 'quality', 'type'])
  }
  assert.equal(requests, 2)
})

