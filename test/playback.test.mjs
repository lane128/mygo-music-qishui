const key = Buffer.from('2b7e151628aed2a6abf7158809cf4f3c', 'hex')
const iv = Buffer.from('f0f1f2f3f4f5f6f7f8f9fafbfcfdfeff', 'hex')
function syntheticAuth() {
  const plain = Buffer.from('0' + key.toString('hex')), inner = Buffer.alloc(plain.length)
  for (let i = 0; i < plain.length; i++) inner[i] = (plain[i] + i.toString(2).replace(/0/g, '').length + 21) ^ (i === 0 ? 0xfa : i === 1 ? 0x55 : inner[i - 2])
  return Buffer.concat([Buffer.from([48 ^ inner[0] ^ inner[1]]), inner]).toString('base64')
}
function encryptedFLAC() {
  const u32 = value => { const b = Buffer.alloc(4); b.writeUInt32BE(value); return b }
  const box = (type, ...parts) => { const data = Buffer.concat(parts); return Buffer.concat([u32(data.length + 8), Buffer.from(type), data]) }
  const full = () => u32(0)
  const encrypt = createCipheriv('aes-128-ctr', key, iv)
  const audio = Buffer.concat([encrypt.update(flac.subarray(42)), encrypt.final()])
  const ftyp = box('ftyp', Buffer.from('isom'), u32(0), Buffer.from('isom'))
  const sinf = box('sinf', box('frma', Buffer.from('fLaC')), box('schm', full(), Buffer.from('cenc'), u32(0x10000)), box('schi', box('tenc', full(), Buffer.from([0, 0, 1, 16]), Buffer.alloc(16))))
  const stsd = box('stsd', full(), u32(1), box('enca', Buffer.alloc(28), box('dfLa', full(), flac.subarray(4, 42)), sinf))
  const movie = offset => box('moov', box('trak', box('mdia', box('minf', box('stbl', stsd, box('stsz', full(), u32(0), u32(1), u32(audio.length)), box('stco', full(), u32(1), u32(offset)), box('stsc', full(), u32(1), u32(1), u32(1), u32(1)), box('senc', full(), u32(1), iv))))))
  return Buffer.concat([ftyp, movie(ftyp.length + movie(0).length + 8), box('mdat', audio)])
}

// The shipped decoder restores the exact synthetic FLAC metadata and PCM frames, and rejects malformed CENC tables.
test('decodes a matching synthetic grant and rejects malformed containers', async () => {
  assert.deepEqual(resourceKey(syntheticAuth()), key)
  const input = encryptedFLAC(), before = Buffer.from(input)
  assert.deepEqual(decodeWithKey(input, key), flac)
  assert.deepEqual(input, before)
  const invalid = Buffer.from(input)
  invalid.writeUInt32BE(1, invalid.indexOf(Buffer.from('stco')) + 12)
  assert.throws(() => decodeWithKey(invalid, key))
  assert.throws(() => decodeWithKey(input.subarray(0, input.length - 1), key))
  if (process.platform === 'darwin') assert.deepEqual(await decodeResource(input, syntheticAuth()), flac)
})

// The native subprocess can read only its executable from protected home, and cannot use network or persistent writes.
test('sandbox denies home reads, external writes and network access', { skip: process.platform !== 'darwin' }, async () => {
  const home = await mkdtemp(path.join(tmpdir(), 'qishui-sandbox-test-'))
  try {
    const root = path.join(home, 'scratch')
    const { mkdir } = await import('node:fs/promises')
    await mkdir(root)
    const secret = path.join(home, 'account.json')
    await writeFile(secret, 'synthetic-private')
    const allowedDir = path.join(home, 'allowed')
    await mkdir(allowedDir)
    const module = path.join(allowedDir, 'fixture.cjs')
    await writeFile(module, 'module.exports = 42')
    const policy = sandboxPolicy(root, [process.execPath, module], home)
    const script = `const fs=require('node:fs'); let denied=0; try {fs.readFileSync(process.argv[1])} catch {denied++}; try {fs.writeFileSync(process.argv[1], 'bad')} catch {denied++}; try {fs.readdirSync(process.argv[3])} catch {denied++}; const loaded=require(process.argv[2])===42; const net=require('node:net'); const s=net.connect(9,'127.0.0.1'); s.on('error',()=>process.exit(denied===3&&loaded?0:1)); s.on('connect',()=>process.exit(1)); setTimeout(()=>process.exit(1),2000)`
    const result = spawnSync('/usr/bin/sandbox-exec', ['-p', policy, process.execPath, '-e', script, secret, module, home], { cwd: root, env: { PATH: '/usr/bin:/bin' }, timeout: 5000 })
    assert.equal(result.status, 0, result.stderr?.toString())
    assert.equal(await readFile(secret, 'utf8'), 'synthetic-private')
  } finally { await rm(home, { recursive: true, force: true }) }
})

